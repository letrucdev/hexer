/// What a piece of the document refers to.
public struct PieceRef: RawRepresentable, Hashable, Sendable, CustomStringConvertible {
    public let rawValue: UInt32
    public init(rawValue: UInt32) { self.rawValue = rawValue }

    /// Bytes typed, pasted or otherwise added during editing, stored in the `AddBuffer`.
    public static let add = PieceRef(rawValue: 0)
    /// A gap with no data, e.g. between records of an Intel Hex file.
    public static let undefined = PieceRef(rawValue: .max)
    private static let generatorFlag: UInt32 = 0x8000_0000

    /// Bytes of a registered `ByteSource` (the opened file, a disk, …).
    public static func source(_ id: UInt32) -> PieceRef {
        precondition(id > 0 && id < generatorFlag)
        return PieceRef(rawValue: id)
    }

    /// Bytes produced on demand by a registered `Generator` (fill patterns, random data).
    public static func generator(_ id: UInt32) -> PieceRef {
        precondition(id < generatorFlag - 1)
        return PieceRef(rawValue: generatorFlag | id)
    }

    public enum Kind: Equatable, Sendable {
        case add, source(UInt32), generator(UInt32), undefined
    }

    public var kind: Kind {
        if self == .add { return .add }
        if self == .undefined { return .undefined }
        if rawValue & Self.generatorFlag != 0 { return .generator(rawValue & ~Self.generatorFlag) }
        return .source(rawValue)
    }

    /// Added and generated bytes count as modified and are highlighted.
    public var isModified: Bool {
        switch kind {
        case .add, .generator: true
        case .source, .undefined: false
        }
    }

    public var description: String {
        switch kind {
        case .add: "add"
        case .undefined: "undefined"
        case .source(let id): "source(\(id))"
        case .generator(let id): "generator(\(id))"
        }
    }
}

/// A run of `length` bytes taken from `ref` starting at `start`.
public struct Piece: Hashable, Sendable, CustomStringConvertible {
    public var ref: PieceRef
    public var start: UInt64
    public var length: UInt64

    public init(_ ref: PieceRef, start: UInt64, length: UInt64) {
        self.ref = ref
        self.start = start
        self.length = length
    }

    public static func undefined(length: UInt64) -> Piece { Piece(.undefined, start: 0, length: length) }

    public func slice(from offset: UInt64, length: UInt64) -> Piece {
        precondition(offset + length <= self.length)
        return Piece(ref, start: ref == .undefined ? 0 : start + offset, length: length)
    }

    /// Whether `next` continues this piece so both can be stored as one.
    public func canMerge(with next: Piece) -> Bool {
        ref == next.ref && (ref == .undefined || start + length == next.start)
    }

    public var description: String { "\(ref)[\(start)+\(length)]" }
}
